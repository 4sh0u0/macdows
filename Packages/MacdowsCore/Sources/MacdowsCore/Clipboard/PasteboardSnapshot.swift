/// What the App observed on the Mac pasteboard at one instant, as plain values: the change
/// count and the type identifiers (`NSPasteboard.PasteboardType` raw values). Taking the
/// snapshot is the App's job, on the main thread; this package never sees `NSPasteboard`.
///
/// Type identifiers are format names, which S9 keeps out of logs too, so this renders only
/// how many there are.
public struct PasteboardSnapshot: Equatable, Sendable {
    public let changeCount: Int
    public let types: [String]

    public init(changeCount: Int, types: [String]) {
        self.changeCount = changeCount
        self.types = types
    }

    /// Whether any type is one of `PasteboardTypes.sensitive` (S2 rule 3, S3 rule 4).
    public var hasSensitiveType: Bool {
        PasteboardTypes.containsSensitive(types)
    }

    /// Whether any type is one of `PasteboardTypes.plainText` (S2 rule 4).
    public var hasPlainTextType: Bool {
        types.contains { PasteboardTypes.plainText.contains($0) }
    }
}

extension PasteboardSnapshot: CustomStringConvertible, CustomDebugStringConvertible, CustomReflectable {
    public var description: String { "PasteboardSnapshot(changeCount: \(changeCount), typeCount: \(types.count))" }
    public var debugDescription: String { description }
    public var customMirror: Mirror {
        Mirror(self, children: ["changeCount": changeCount, "typeCount": types.count], displayStyle: .struct)
    }
}

/// The pasteboard type identifiers the T1 decisions look for.
public enum PasteboardTypes {
    /// The nspasteboard.org markers (S2/S3's "sensitive markers"). Password managers and similar tools set
    /// them on content that must not be retained or shared; T1 never announces or sends a
    /// pasteboard that carries any of them.
    public static let sensitive: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    /// Whether `types` contains any of `sensitive`. One definition for the snapshot (S2) and
    /// for S3 rule 4, which reads the type list on its own, without a change count.
    public static func containsSensitive(_ types: [String]) -> Bool {
        types.contains { sensitive.contains($0) }
    }

    /// Identifiers that count as "the pasteboard has text" for S2 rule 4. Broad on purpose:
    /// announcing text the App then cannot read costs one failed answer (S3 rule 5), while a
    /// missing identifier silently stops a real copy from being shared. Which of these the
    /// App's actual text read can be served from is the App's to verify (unverified here).
    public static let plainText: Set<String> = [
        "public.utf8-plain-text",
        "public.utf16-plain-text",
        "public.utf16-external-plain-text",
        "public.plain-text",
        "NSStringPboardType",
    ]
}

/// The Mac side's memory of its own writes (S2 rule 2, the anti-loop rule): when the App writes
/// remote text to the pasteboard it adds a private marker type and records the change count
/// the write produced. A later snapshot with that change count, or carrying the marker, is
/// remote text coming back around and must not be announced to Windows -- announcing it would
/// replace whatever richer formats Windows still holds with a text-only copy.
///
/// Deliberately NOT cleared by a disconnect (S8): the remote text already written stays on the
/// pasteboard as real data, and it is still remote text after a reconnect.
public struct PasteboardOwnership: Equatable, Sendable {
    /// The design's suggested marker name; the App (L4) decides the final one and may pass it.
    public static let defaultMarkerType = "dev.macdows.remote-clipboard"

    public let markerType: String
    public private(set) var lastOwnWriteChangeCount: Int?

    public init(markerType: String = PasteboardOwnership.defaultMarkerType) {
        self.markerType = markerType
        self.lastOwnWriteChangeCount = nil
    }

    /// Records the change count the pasteboard reported right after the App wrote remote text.
    public mutating func recordOwnWrite(changeCount: Int) {
        lastOwnWriteChangeCount = changeCount
    }

    /// Whether `snapshot` is the App's own most recent write, by change count.
    public func isOwnWrite(_ snapshot: PasteboardSnapshot) -> Bool {
        lastOwnWriteChangeCount == snapshot.changeCount
    }

    /// Whether `snapshot` carries the App's marker type.
    public func carriesMarker(_ snapshot: PasteboardSnapshot) -> Bool {
        snapshot.types.contains(markerType)
    }
}
